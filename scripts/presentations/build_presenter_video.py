#!/usr/bin/env python3
"""Build a narrated video from presenter script markdown + Reveal.js HTML slides.

This script:
1. Parses the presenter script markdown (6_presenter_script.md)
2. Synthesizes narration audio using Gemini TTS
3. Captures slide screenshots from the Reveal.js HTML presentation
4. Combines audio + slides into a synchronized MP4 video

Slide synchronization:
    Uses the slide mapping JSON (*_slide_mapping.json) generated by md_to_revealjs.py
    to correctly map markdown slide numbers to HTML section indices. This is critical
    because slides with figures generate TWO HTML sections (main + zoom companion).

    If the mapping JSON is missing, falls back to naive slide_number - 1 calculation,
    which will produce incorrect slide sync when figures are present.

Requirements:
- Node.js + npx (for Playwright CLI)
- ffmpeg (for video encoding)
- Python packages: see requirements.txt
"""

