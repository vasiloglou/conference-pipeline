def _load_json_object(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"{path} must contain a JSON object")
    return payload


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _isoformat_z() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def _infer_workspace(path: Path) -> Path:
    parts = path.resolve().parts
    if "decks" in parts:
        index = parts.index("decks")
        return Path(*parts[:index])
    return path.parent


def _relative(path: Path, root: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def _delivery_script_payload(
    *,
    delivery_contract: Path,
    style: str,
    voice_label: str,
) -> dict[str, Any]:
    payload = _load_json_object(delivery_contract)
    segments = [
        segment
        for segment in payload.get("segments", [])
        if isinstance(segment, dict) and str(segment.get("narration") or "").strip()
    ]
    if not segments:
        raise SystemExit(f"{delivery_contract} contains no narration segments.")
    script_segments: list[dict[str, str]] = []
    script_slide_metadata: list[dict[str, Any]] = []
    for source_index, segment in enumerate(segments, start=1):
        narration = normalize_space(str(segment.get("narration") or ""))
        speaker = str(segment.get("speaker") or voice_label)
        turns = (
            _notebooklm_delivery_turns(narration, fallback_speaker=voice_label)
            if style == "notebooklm"
            else [(speaker, narration)]
        )
        for turn_index, (turn_speaker, turn_text) in enumerate(turns, start=1):
            if not turn_text:
                continue
            script_segments.append({"speaker": turn_speaker, "text": turn_text})
            script_slide_metadata.append(
                {
                    "segment": len(script_segments),
                    "source_segment": source_index,
                    "source_turn": turn_index,
                    "slide_number": segment.get("slide_number"),
                    "slide_id": segment.get("slide_id"),
                    "segment_id": segment.get("segment_id"),
                }
            )
    if not script_segments:
        raise SystemExit(f"{delivery_contract} contains no spoken narration turns.")
    return {
        "schema_version": 1,
        "title": str(payload.get("presentation_id") or delivery_contract.parent.name),
        "summary": f"{style} narration generated from the reviewed delivery contract.",
        "segments": script_segments,
        "metadata": {
            "delivery_contract": str(delivery_contract),
            "delivery_variant": style,
            "slides": script_slide_metadata,
        },
    }


def _notebooklm_delivery_turns(text: str, *, fallback_speaker: str) -> list[tuple[str, str]]:
    markers = list(re.finditer(r"\b(Host [AB])\s+", text))
    if len({match.group(1) for match in markers}) < 2:
        return [(fallback_speaker, text)]
    turns: list[tuple[str, str]] = []
    for index, match in enumerate(markers):
        start = match.end()
        end = markers[index + 1].start() if index + 1 < len(markers) else len(text)
        turn_text = normalize_space(text[start:end])
        if turn_text:
            turns.append((match.group(1), turn_text))
    return turns or [(fallback_speaker, text)]


def _content_frame_paths_for_delivery(
    delivery_contract: Path,
    *,
    slide_numbers: list[int],
) -> list[Path]:
    deck_dir = delivery_contract.parent
    manifest_path = deck_dir / "slide_frame_manifest.json"
    manifest = _load_json_object(manifest_path)
    frames = [
        frame
        for frame in manifest.get("frames", [])
        if isinstance(frame, dict) and str(frame.get("slide_id") or "") != "title"
    ]
    frames.sort(key=lambda frame: int(frame.get("frame_order") or frame.get("index") or 0))
    if not frames:
        raise SystemExit(f"{manifest_path} has no content slide frames.")
    paths: list[Path] = []
    for raw_number in slide_numbers:
        if not isinstance(raw_number, int) or isinstance(raw_number, bool):
            raise SystemExit(f"delivery segment lacks numeric slide_number: {delivery_contract}")
        if raw_number < 1 or raw_number > len(frames):
            raise SystemExit(
                f"delivery slide_number {raw_number} is outside frame manifest range 1..{len(frames)}"
            )
        raw_path = frames[raw_number - 1].get("path") or frames[raw_number - 1].get("frame_path")
        frame_path = (deck_dir / str(raw_path)).resolve()
        if not frame_path.is_file():
            raise SystemExit(f"declared slide frame is missing: {frame_path}")
        paths.append(frame_path)
    if not paths:
        raise SystemExit(f"{delivery_contract} has no frame-mappable segments.")
    return paths


def _provider_receipts_since(*, workspace: Path, start_epoch: float) -> list[str]:
    roots = [
        REPO_ROOT / "storage" / "provider-calls" / "synthesize_audio_from_script",
        workspace / "storage" / "provider-calls" / "synthesize_audio_from_script",
    ]
    paths: list[Path] = []
    for root in roots:
        if root.is_dir():
            paths.extend(
                path
                for path in root.glob("*.json")
                if path.is_file() and path.stat().st_mtime >= start_epoch - 1.0
            )
    return [_relative(path, REPO_ROOT) for path in sorted(set(paths))]


def _detect_silence_spans(path: Path) -> list[tuple[float, float]]:
    completed = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-nostats",
            "-i",
            str(path),
            "-af",
            "silencedetect=noise=-35dB:d=0.25",
            "-f",
            "null",
            "-",
        ],
        check=False,
        capture_output=True,
        text=True,
        timeout=120,
    )
    output = completed.stdout + "\n" + completed.stderr
    starts = [float(value) for value in re.findall(r"silence_start:\s*([0-9.]+)", output)]
    ends = [float(value) for value in re.findall(r"silence_end:\s*([0-9.]+)", output)]
    return list(zip(starts, ends, strict=False))


def _silence_voice_gap_summary(audio_path: Path) -> dict[str, Any]:
    duration = probe_duration(audio_path)
    spans = _detect_silence_spans(audio_path)
    lengths = [max(0.0, end - start) for start, end in spans]
    total = sum(lengths)
    longest = max(lengths, default=0.0)
    return {
        "duration_seconds": round(duration, 4),
        "silence_spans": [
            {"start_seconds": round(start, 4), "end_seconds": round(end, 4)}
            for start, end in spans
        ],
        "silence_span_count": len(spans),
        "longest_silence_seconds": round(longest, 4),
        "total_silence_seconds": round(total, 4),
        "total_silence_ratio": round(total / duration, 4) if duration else 1.0,
        "voice_gap_threshold_seconds": 5.0,
    }


def _write_delivery_slide_concat(
    *,
    frame_paths: list[Path],
    audio_paths: list[Path],
    slides_concat_path: Path,
) -> None:
    if len(frame_paths) != len(audio_paths):
        raise SystemExit(
            f"frame/audio segment mismatch: {len(frame_paths)} frames for {len(audio_paths)} audio files"
        )
    lines: list[str] = []
    for frame_path, audio_path in zip(frame_paths, audio_paths, strict=True):
        lines.append(f"file '{frame_path.resolve().as_posix()}'")
        lines.append(f"duration {probe_duration(audio_path):.6f}")
    lines.append(f"file '{frame_paths[-1].resolve().as_posix()}'")
    slides_concat_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_audio_receipt(
    *,
    delivery_contract: Path,
    script_json: Path,
    audio_paths: list[Path],
    narration_audio: Path,
    provider_receipt_refs: list[str],
    audio_model: str,
    voice: str,
    style: str,
) -> Path:
    deck_dir = delivery_contract.parent
    workspace = _infer_workspace(deck_dir)
    suffix = "single_speaker" if style == "single_speaker" else "notebooklm"
    receipt_path = deck_dir / f"narration_audio_receipt_{suffix}.json"
    segment_refs = [
        {
            "index": index,
            "path": _relative(path, workspace),
            "sha256": _sha256_file(path),
            "byte_count": path.stat().st_size,
            "duration_seconds": round(probe_duration(path), 4),
        }
        for index, path in enumerate(audio_paths, start=1)
    ]
    payload = {
        "schema_version": 1,
        "generated_at": _isoformat_z(),
        "status": "pass",
        "presentation_id": deck_dir.name,
        "delivery_variant": style,
        "script_json_path": _relative(script_json, workspace),
        "script_json_sha256": _sha256_file(script_json),
        "delivery_contract_path": _relative(delivery_contract, workspace),
        "delivery_contract_sha256": _sha256_file(delivery_contract),
        "audio_segment_refs": segment_refs,
        "audio_segment_count": len(segment_refs),
        "narration_track_path": _relative(narration_audio, workspace),
        "narration_track_sha256": _sha256_file(narration_audio),
        "byte_count": narration_audio.stat().st_size,
        "duration_seconds": round(probe_duration(narration_audio), 4),
        "silence_voice_gap_summary": _silence_voice_gap_summary(narration_audio),
        "provider_receipt_refs": provider_receipt_refs,
        "model_receipt_refs": [
            {
                "provider": "google-gemini",
                "model": audio_model,
                "voice": voice,
            }
        ],
        "cost_receipt_refs": provider_receipt_refs,
        "audio_source": "live_tts" if provider_receipt_refs else "cached_tts",
        "synthetic_audio": False,
        "fixture_audio": False,
        "production_evidence": bool(segment_refs and narration_audio.stat().st_size > 0),
    }
    receipt_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return receipt_path


def build_delivery_contract_video(
    *,
    delivery_contract: Path,
    slides_html: Path,
    slide_mapping: Path | None,
    build_dir: Path,
    output_video: Path,
    style: str,
    dry_run: bool,
    audio_model: str,
    voice: str,
) -> dict[str, Any]:
    """Build a production canary video from delivery text, live TTS, and rendered frames."""

    delivery_contract = delivery_contract.resolve()
    slides_html = slides_html.resolve()
    build_dir = build_dir.resolve()
    output_video = output_video.resolve()
    deck_dir = delivery_contract.parent
    workspace = _infer_workspace(deck_dir)
    delivery_payload = _load_json_object(delivery_contract)
    segments = [segment for segment in delivery_payload.get("segments", []) if isinstance(segment, dict)]
    plan = {
        "builder": "scripts/presentations/build_presenter_video.py",
        "delivery_contract": str(delivery_contract),
        "dry_run": dry_run,
        "output": str(output_video),
        "segment_count": len(segments),
        "slide_mapping": str(slide_mapping) if slide_mapping else None,
        "slides_html": str(slides_html),
        "style": style,
        "provider_requirements": ["tool:ffmpeg", "env:GEMINI_API_KEY|GOOGLE_API_KEY"],
        "production_evidence": not dry_run,
    }
    if dry_run:
        return plan
    if not slides_html.is_file():
        raise SystemExit(f"Slides HTML not found: {slides_html}")
    build_dir.mkdir(parents=True, exist_ok=True)
    output_video.parent.mkdir(parents=True, exist_ok=True)

    script_payload = _delivery_script_payload(
        delivery_contract=delivery_contract,
        style=style,
        voice_label="Presenter" if style == "single_speaker" else "Host A / Host B",
    )
    script_segments = [
        segment for segment in script_payload.get("segments", []) if isinstance(segment, dict)
    ]
    slide_metadata = [
        slide for slide in script_payload.get("metadata", {}).get("slides", []) if isinstance(slide, dict)
    ]
    slide_numbers = [slide.get("slide_number") for slide in slide_metadata]
    script_json = build_dir / "script.json"
    script_json.write_text(
        json.dumps(script_payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    validate_tts_script_json_payload(script_payload)

    _load_repo_env()
    provider_start = time.time()
    speaker_voices: list[tuple[str, str]] | None = None
    if style == "notebooklm":
        delivery_style = _load_json_object(delivery_contract).get("style") or {}
        host_a = str(delivery_style.get("host_a") or "").strip()
        host_b = str(delivery_style.get("host_b") or "").strip()
        if host_a and host_b:
            voice_a = str(delivery_style.get("voice_a") or host_a).strip()
            voice_b = str(delivery_style.get("voice_b") or host_b).strip()
            speaker_voices = [(host_a, voice_a), (host_b, voice_b)]
    synthesize_audio(script_json, audio_model=audio_model, voice=voice, speaker_voices=speaker_voices)
    provider_receipt_refs = _provider_receipts_since(workspace=workspace, start_epoch=provider_start)

    audio_dir = build_dir / "audio_segments"
    audio_paths = [find_audio_segment(audio_dir, index) for index in range(1, len(script_segments) + 1)]
    frame_paths = _content_frame_paths_for_delivery(
        delivery_contract,
        slide_numbers=slide_numbers,
    )
    audio_concat = build_dir / "audio_concat.txt"
    slides_concat = build_dir / "slides_concat.txt"
    narration_audio = build_dir / "narration_track.m4a"
    slides_track = build_dir / "slides_track.mp4"
    audio_concat.write_text(
        "\n".join(f"file '{path.resolve().as_posix()}'" for path in audio_paths) + "\n",
        encoding="utf-8",
    )
    _write_delivery_slide_concat(
        frame_paths=frame_paths,
        audio_paths=audio_paths,
        slides_concat_path=slides_concat,
    )
    concat_audio(audio_concat, narration_audio)
    build_slides_track(slides_concat, slides_track)
    mux_video(slides_track, narration_audio, output_video)
    receipt_path = _write_audio_receipt(
        delivery_contract=delivery_contract,
        script_json=script_json,
        audio_paths=audio_paths,
        narration_audio=narration_audio,
        provider_receipt_refs=provider_receipt_refs,
        audio_model=audio_model,
        voice=voice,
        style=style,
    )
    return {
        **plan,
        "dry_run": False,
        "script_json": str(script_json),
        "narration_audio": str(narration_audio),
        "audio_receipt": str(receipt_path),
        "provider_receipt_refs": provider_receipt_refs,
    }


def run_cmd(cmd: list[str], *, cwd: Path | None = None) -> None:
    subprocess.run(cmd, cwd=cwd, check=True)


def run_cmd_capture(cmd: list[str], *, cwd: Path | None = None) -> str:
    result = subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True)
    return result.stdout.strip()


def normalize_space(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def strip_markdown_prefixes(line: str) -> str:
    cleaned = line.strip()
    cleaned = re.sub(r"^>\s*", "", cleaned)
    cleaned = re.sub(r"^[-*]\s+", "", cleaned)
    return cleaned.strip()


def extract_named_block(block: str, name: str) -> str:
    target = name.strip().upper()
    labels = list(BLOCK_LABEL_RE.finditer(block))
    for index, match in enumerate(labels):
        if match.group("name").strip().upper() != target:
            continue
        next_start = labels[index + 1].start() if index + 1 < len(labels) else len(block)
        separator_match = re.search(r"(?m)^---\s*$", block[match.end() : next_start])
        if separator_match:
            next_start = match.end() + separator_match.start()

        body = block[match.end() : next_start].strip()
        tail = _spoken_label_tail(target, match.group("tail"))
        if tail:
            body = f"{tail}\n{body}".strip() if body else tail
        return body.strip()
    return ""


def _spoken_label_tail(name: str, tail: str) -> str:
    cleaned = tail.strip()
    if not cleaned:
        return ""
    if name in {"CONTEXT", "REFS"}:
        return ""
    cleaned = re.sub(r"^:\s*", "", cleaned).strip()
    if cleaned.startswith("(") and name not in {"SAY", "TRANSITION", "FIGURE"}:
        return ""
    return cleaned


def parse_context_block(raw: str, max_items: int) -> list[str]:
    if not raw:
        return []
    items: list[str] = []
    for line in raw.splitlines():
        cleaned = strip_markdown_prefixes(line)
        if not cleaned:
            continue
        items.append(normalize_space(cleaned))
        if len(items) >= max_items:
            break
    return items


def parse_transition_block(raw: str) -> str | None:
    if not raw:
        return None
    lines = [strip_markdown_prefixes(line) for line in raw.splitlines() if strip_markdown_prefixes(line)]
    if not lines:
        return None
    text = normalize_space(" ".join(lines))
    text = text.strip().strip('"').strip()
    return text or None


def load_slide_mapping_keys(mapping_path: Path) -> set[int]:
    """Return logical markdown slide numbers declared by a slide mapping file."""
    try:
        raw = json.loads(mapping_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise SystemExit(f"Could not read slide mapping {mapping_path}: {exc}") from exc
    if not isinstance(raw, dict):
        raise SystemExit(f"Slide mapping must be a JSON object: {mapping_path}")

    slides = raw.get("slides")
    if isinstance(slides, list):
        mapped: set[int] = set()
        for index, item in enumerate(slides):
            if not isinstance(item, dict):
                raise SystemExit(f"Slide mapping slides[{index}] must be an object: {mapping_path}")
            raw_number = item.get("slide_number", item.get("markdown_slide", index))
            if not isinstance(raw_number, int) or isinstance(raw_number, bool):
                raise SystemExit(
                    f"Slide mapping slides[{index}].slide_number must be an integer: {mapping_path}"
                )
            mapped.add(raw_number)
        return mapped

    mapped = set()
    for key in raw:
        if not isinstance(key, str) or not key.isdigit():
            continue
        mapped.add(int(key))
    if not mapped:
        raise SystemExit(f"Slide mapping contains no logical slide numbers: {mapping_path}")
    return mapped


def validate_slide_mapping_coverage(
    *,
    entries: list[SlideNarration],
    slide_mapping: Path | None,
) -> None:
    """Fail before media generation if narration omits mapped slides."""
    if slide_mapping is None:
        return
    mapped = load_slide_mapping_keys(slide_mapping)
    narrated = {entry.slide_number for entry in entries}
    missing = sorted(mapped - narrated)
    if missing:
        preview = ", ".join(str(n) for n in missing[:12])
        suffix = "" if len(missing) <= 12 else f", ... (+{len(missing) - 12} more)"
        raise SystemExit(
            f"Presenter script is missing narration for mapped slide(s): {preview}{suffix}. "
            "Regenerate the presenter script after rebuilding presentation.html so video timing "
            "stays aligned with title and topic slides."
        )


def compose_context_sentence(items: list[str], prefix: str) -> str | None:
    if not items:
        return None
    fragments = [normalize_space(item).rstrip(" .;") for item in items if normalize_space(item)]
    if not fragments:
        return None
    if len(fragments) == 1:
        body = fragments[0]
    elif len(fragments) == 2:
        body = f"{fragments[0]}, and {fragments[1]}"
    else:
        body = "; ".join(fragments[:-1]) + f"; and {fragments[-1]}"
    return f"{prefix}, {body}."


def compose_narration(
    *,
    say: str,
    context_items: list[str],
    transition: str | None,
    context_prefix: str,
) -> str:
    parts: list[str] = []

    say_text = normalize_space(" ".join(strip_markdown_prefixes(line) for line in say.splitlines() if line.strip()))
    if say_text:
        parts.append(_ensure_sentence_punctuation(say_text))

    if transition:
        t = normalize_space(transition).strip().strip('"').strip()
        if t:
            parts.append(_ensure_sentence_punctuation(t))

    return " ".join(parts).strip()


def _ensure_sentence_punctuation(text: str) -> str:
    stripped = text.strip()
    if not stripped:
        return ""
    if re.search(r"[.!?][\"')\]]*$", stripped):
        return stripped
    return f"{stripped}."


def parse_presenter_script(
    path: Path, *, max_context_items: int, context_prefix: str
) -> list[SlideNarration]:
    text = path.read_text(encoding="utf-8")
    headers = list(re.finditer(r"(?m)^### \[SLIDE\s+(\d+)\]\s*(.+)$", text))
    if not headers:
        parsed_simple = parse_simple_presenter_script(
            text,
            max_context_items=max_context_items,
            context_prefix=context_prefix,
        )
        if parsed_simple:
            return parsed_simple
        raise SystemExit(f"No slide headers found in presenter script: {path}")

    parsed: list[SlideNarration] = []
    for i, match in enumerate(headers, start=1):
        slide_number = int(match.group(1))
        title = normalize_space(match.group(2))
        start = match.end()
        end = headers[i].start() if i < len(headers) else len(text)
        block = text[start:end]

        say_raw = extract_named_block(block, "SAY")
        context_raw = extract_named_block(block, "CONTEXT")
        transition_raw = extract_named_block(block, "TRANSITION")

        context_items = parse_context_block(context_raw, max_context_items)
        transition = parse_transition_block(transition_raw)
        narration = compose_narration(
            say=say_raw,
            context_items=context_items,
            transition=transition,
            context_prefix=context_prefix,
        )
        if not narration:
            continue

        parsed.append(
            SlideNarration(
                index=len(parsed) + 1,
                slide_number=slide_number,
                title=title,
                say=normalize_space(say_raw),
                context=context_items,
                transition=transition,
                narration=narration,
            )
        )

    return parsed


def parse_simple_presenter_script(
    text: str,
    *,
    max_context_items: int,
    context_prefix: str,
) -> list[SlideNarration]:
    """Parse compact executive-summary presenter scripts.

    Executive overview decks are generated with `## Slide N: Title` sections
    rather than the richer topic-deck `### [SLIDE N]` blocks.
    """
    headers = list(re.finditer(r"(?m)^## Slide\s+(\d+):\s*(.+)$", text))
    if not headers:
        return []

    parsed: list[SlideNarration] = []
    title_match = re.search(r"(?m)^# Presenter Script:\s*(.+)$", text)
    if title_match:
        deck_title = normalize_space(title_match.group(1))
        parsed.append(
            SlideNarration(
                index=1,
                slide_number=0,
                title=deck_title,
                say=deck_title,
                context=[],
                transition=None,
                narration=f"Welcome to {deck_title}.",
            )
        )

    for i, match in enumerate(headers, start=1):
        slide_number = int(match.group(1))
        title = normalize_space(match.group(2))
        start = match.end()
        end = headers[i].start() if i < len(headers) else len(text)
        block = text[start:end].strip()
        say_raw = extract_named_block(block, "SAY")
        if not say_raw:
            continue
        context_raw = extract_named_block(block, "CONTEXT")
        transition_raw = extract_named_block(block, "TRANSITION")
        context_items = parse_context_block(context_raw, max_context_items)
        transition = parse_transition_block(transition_raw)
        narration = compose_narration(
            say=say_raw,
            context_items=context_items,
            transition=transition,
            context_prefix=context_prefix,
        )
        if not narration:
            continue
        parsed.append(
            SlideNarration(
                index=len(parsed) + 1,
                slide_number=slide_number,
                title=title,
                say=normalize_space(say_raw),
                context=context_items,
                transition=transition,
                narration=narration,
            )
        )

    parsed_content_slide_count = len(parsed) - (1 if title_match else 0)
    if parsed_content_slide_count < len(headers):
        raise SystemExit(
            "Compact presenter script contains slide outlines without **SAY:** blocks. "
            "Regenerate executive-summary presenter narration before building TTS JSON."
        )
    return parsed


def write_script_json(entries: list[SlideNarration], script_json: Path, title: str) -> None:
    payload = {
        "title": title,
        "summary": "Narration derived from spoken SAY and TRANSITION fields.",
        "segments": [{"speaker": "Presenter", "text": entry.narration} for entry in entries],
        "metadata": {
            "slides": [
                {
                    "segment": entry.index,
                    "slide_number": entry.slide_number,
                    "title": entry.title,
                    "say": entry.say,
                    "context_count": len(entry.context),
                    "transition": entry.transition,
                }
                for entry in entries
            ]
        },
    }
    validate_tts_script_json_payload(payload)
    script_json.parent.mkdir(parents=True, exist_ok=True)
    script_json.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def validate_tts_script_json_payload(payload: dict[str, object]) -> None:
    failures: list[str] = []
    segments = payload.get("segments")
    if not isinstance(segments, list):
        raise SystemExit("Presenter script JSON payload must contain a segments list.")
    for index, segment in enumerate(segments, start=1):
        if not isinstance(segment, dict):
            failures.append(f"segment {index}: segment is not an object")
            continue
        text = str(segment.get("text") or "")
        for rule, pattern in FORBIDDEN_TTS_TEXT_PATTERNS:
            if pattern.search(text):
                failures.append(f"segment {index}: {rule}")
    if failures:
        preview = "; ".join(failures[:8])
        suffix = "" if len(failures) <= 8 else f"; ... (+{len(failures) - 8} more)"
        raise SystemExit(f"Presenter script JSON contains non-spoken TTS text: {preview}{suffix}")


