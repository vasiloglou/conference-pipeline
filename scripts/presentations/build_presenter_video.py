def capture_slides(
    entries: list[SlideNarration],
    *,
    slides_html: Path,
    slides_dir: Path,
    wait_ms: int,
    viewport: str,
    workers: int,
) -> list[tuple[Path, float]]:
    """Capture slide screenshots. Returns list of (path, duration_fraction) tuples.

    For slides with zoom companions, captures both main and zoom, returning:
    - (slide_001_main.png, 0.7) - main slide shown for 70% of narration
    - (slide_001_zoom.png, 0.3) - zoom shown for 30% of narration

    For slides without zoom, returns:
    - (slide_001.png, 1.0) - single slide shown for full narration
    """
    # Verify Playwright CLI is available before looping.
    run_cmd(["npx", "playwright", "--version"], cwd=REPO_ROOT)

    slides_dir.mkdir(parents=True, exist_ok=True)
    html_url = slides_html.resolve().as_uri()
    slide_items: list[tuple[Path, float]] = []
    capture_jobs: list[tuple[str, Path]] = []

    # Load slide mapping JSON to convert markdown slide numbers to HTML section indices
    mapping_json = slides_html.parent / f"{slides_html.stem}_slide_mapping.json"
    slide_mapping = {}
    if mapping_json.exists():
        with open(mapping_json, 'r', encoding='utf-8') as f:
            raw_mapping = json.load(f)
            # Convert string keys to integers
            slide_mapping = {int(k): v for k, v in raw_mapping.items()}
        print(f"✓ Loaded slide mapping: {len(slide_mapping)} slides")
    else:
        print(f"⚠️  Slide mapping not found: {mapping_json}")
        print(f"   Falling back to naive slide_number - 1 calculation (may be incorrect)")

    for entry in entries:
        # Use slide mapping if available, otherwise fall back to naive calculation
        if slide_mapping:
            main_index = slide_mapping.get(entry.slide_number, max(entry.slide_number - 1, 0))
        else:
            main_index = max(entry.slide_number - 1, 0)

        # Detect if this slide has a zoom companion by checking if next slide has a gap
        has_zoom = False
        if slide_mapping and entry.slide_number in slide_mapping:
            # Get the next markdown slide number
            next_slide_num = entry.slide_number + 1
            if next_slide_num in slide_mapping:
                next_index = slide_mapping[next_slide_num]
                # If gap > 1, current slide has a zoom companion
                has_zoom = (next_index - main_index) > 1
            else:
                # This is the last slide, check total HTML sections to detect zoom
                # For now, assume no zoom if it's the last slide (we'd need total count)
                pass

        if has_zoom:
            # Capture main slide (70% of narration time)
            main_output = slides_dir / f"slide_{entry.index:03d}_main.png"
            if not main_output.exists():
                url = f"{html_url}#/{main_index}"
                capture_jobs.append((url, main_output))
            slide_items.append((main_output, 0.7))

            # Capture zoom slide (30% of narration time)
            zoom_output = slides_dir / f"slide_{entry.index:03d}_zoom.png"
            zoom_index = main_index + 1
            if not zoom_output.exists():
                url = f"{html_url}#/{zoom_index}"
                capture_jobs.append((url, zoom_output))
            slide_items.append((zoom_output, 0.3))

        else:
            # No zoom companion - single slide for full narration
            output = slides_dir / f"slide_{entry.index:03d}.png"
            if not output.exists():
                url = f"{html_url}#/{main_index}"
                capture_jobs.append((url, output))
            slide_items.append((output, 1.0))

    def capture_one(job: tuple[str, Path]) -> Path:
        url, output = job
        cmd = [
            "npx",
            "playwright",
            "screenshot",
            url,
            str(output),
            "--viewport-size",
            viewport,
            "--wait-for-timeout",
            str(wait_ms),
        ]
        last_error: subprocess.CalledProcessError | None = None
        for attempt in range(1, 4):
            try:
                run_cmd(cmd, cwd=REPO_ROOT)
                return output
            except subprocess.CalledProcessError as exc:
                last_error = exc
                if attempt < 3:
                    time.sleep(1.5 * attempt)
        assert last_error is not None
        raise last_error
        return output

    if capture_jobs:
        worker_count = max(1, workers)
        print(f"Capturing {len(capture_jobs)} slide images with {worker_count} workers.")
        if worker_count == 1:
            for job in capture_jobs:
                capture_one(job)
        else:
            with concurrent.futures.ThreadPoolExecutor(max_workers=worker_count) as executor:
                futures = [executor.submit(capture_one, job) for job in capture_jobs]
                for future in concurrent.futures.as_completed(futures):
                    future.result()

    return slide_items


def find_audio_segment(audio_dir: Path, idx: int) -> Path:
    mp3 = audio_dir / f"segment_{idx:03d}_01.mp3"
    wav = audio_dir / f"segment_{idx:03d}_01.wav"
    if mp3.exists():
        return mp3
    if wav.exists():
        return wav
    raise SystemExit(f"Missing audio segment for index {idx}: expected {mp3.name} or {wav.name}")


def probe_duration(audio_path: Path) -> float:
    out = run_cmd_capture(
        [
            "ffprobe",
            "-v",
            "quiet",
            "-show_entries",
            "format=duration",
            "-of",
            "csv=p=0",
            str(audio_path),
        ]
    )
    try:
        return float(out)
    except ValueError:
        raise SystemExit(
            f"ffprobe could not read a duration from {audio_path} (got {out!r}); the file is not "
            "decodable audio -- a raw PCM TTS response saved under an .mp3 name is the usual cause "
            "(synthesize_audio_from_script converts by sniffing the bytes; re-run the synthesis)"
        ) from None


def write_concat_files(
    *,
    slide_items: list[tuple[Path, float]],
    audio_paths: list[Path],
    audio_concat_path: Path,
    slides_concat_path: Path,
) -> None:
    """Write ffmpeg concat files for audio and slides.

    slide_items: list of (path, duration_fraction) tuples
    - For slides with zoom: [(main.png, 0.7), (zoom.png, 0.3)]
    - For slides without: [(slide.png, 1.0)]
    """
    audio_lines = [f"file '{p.resolve().as_posix()}'" for p in audio_paths]
    audio_concat_path.write_text("\n".join(audio_lines) + "\n", encoding="utf-8")

    grouped_slide_items: list[list[tuple[Path, float]]] = []
    current_group: list[tuple[Path, float]] = []
    current_fraction = 0.0
    tolerance = 0.000001
    for slide_path, duration_fraction in slide_items:
        current_group.append((slide_path, duration_fraction))
        current_fraction += duration_fraction
        if current_fraction > 1.0 + tolerance:
            raise SystemExit("Slide duration fractions exceed one narration segment.")
        if current_fraction >= 1.0 - tolerance:
            grouped_slide_items.append(current_group)
            current_group = []
            current_fraction = 0.0
    if current_group:
        raise SystemExit("Slide duration fractions do not complete a narration segment.")
    if len(grouped_slide_items) != len(audio_paths):
        raise SystemExit(
            "Slide narration groups do not match audio segment count: "
            f"{len(grouped_slide_items)} slide groups for {len(audio_paths)} audio files."
        )

    slide_lines: list[str] = []
    for audio_path, visual_group in zip(audio_paths, grouped_slide_items, strict=True):
        audio_duration = probe_duration(audio_path)
        for slide_path, duration_fraction in visual_group:
            display_duration = audio_duration * duration_fraction
            slide_lines.append(f"file '{slide_path.resolve().as_posix()}'")
            slide_lines.append(f"duration {display_duration:.6f}")

    # Add final slide (required by ffmpeg concat format)
    final_slide_path = slide_items[-1][0]
    slide_lines.append(f"file '{final_slide_path.resolve().as_posix()}'")
    slides_concat_path.write_text("\n".join(slide_lines) + "\n", encoding="utf-8")


def concat_audio(audio_concat: Path, output_audio: Path) -> None:
    cmd_copy = [
        "ffmpeg",
        "-y",
        "-f",
        "concat",
        "-safe",
        "0",
        "-i",
        str(audio_concat),
        "-c",
        "copy",
        str(output_audio),
    ]
    try:
        run_cmd(cmd_copy)
    except subprocess.CalledProcessError:
        cmd_encode = [
            "ffmpeg",
            "-y",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(audio_concat),
            "-c:a",
            "aac",
            "-b:a",
            "192k",
            str(output_audio),
        ]
        run_cmd(cmd_encode)


