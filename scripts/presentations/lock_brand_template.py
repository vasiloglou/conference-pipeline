#!/usr/bin/env python3
"""Write 01-BRAND-REFERENCE-LOCK.md and 01-BRAND-REFERENCE-LOCK.json.

Usage:
    python scripts/presentations/lock_brand_template.py \\
        --workspace /path/to/workspace \\
        --deck-dir conferences/iclr2026/decks/01_reasoning_post_training \\
        --output-md .planning/.../01-BRAND-REFERENCE-LOCK.md \\
        --output-json .planning/.../01-BRAND-REFERENCE-LOCK.json

    # Dry run (no files written):
    python scripts/presentations/lock_brand_template.py --dry-run ...
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from dataclasses import asdict
from datetime import timezone, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent / "src"))

from conference_pipeline.presentation.brand_template import (
    BrandTemplateLock,
    brand_assets_sha256,
    validate_brand_template_lock,
    BRAND_REFERENCE_NAME,
    RENDERER_GEOMETRY,
    CSS_VARIABLES,
)


def _resolve_inside_workspace(root: Path, candidate: str | Path, *, label: str) -> Path:
    path = Path(candidate).expanduser()
    if not path.is_absolute():
        path = root / path
    resolved = path.resolve()
    try:
        resolved.relative_to(root.resolve())
    except ValueError as exc:
        raise ValueError(f"{label} must stay inside the workspace: {resolved}") from exc
    return resolved


def _write_atomic(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", dir=path.parent, delete=False, suffix=".tmp"
    ) as tmp:
        json.dump(payload, tmp, indent=2)
        tmp_path = Path(tmp.name)
    tmp_path.replace(path)


def _build_markdown(lock: BrandTemplateLock, reference_deck_path: str) -> str:
    lines: list[str] = []
    lines.append("# Brand Reference Lock")
    lines.append("")
    lines.append(f"**Status:** `{lock.status}`  ")
    lines.append(f"**Generated:** {lock.generated_at}  ")
    lines.append(f"**Generated by:** `scripts/presentations/lock_brand_template.py`")
    lines.append("")
    lines.append("## Canonical Reference")
    lines.append("")
    lines.append(f"- **Reference name:** `{lock.reference_name}`")
    lines.append(f"- **Reference deck path:** `{lock.reference_deck_path or reference_deck_path}`")
    lines.append(f"- **Asset SHA-256:** `{lock.template_sha256 or '(empty — assets missing)'}`")
    lines.append("")
    lines.append("## Required Asset Roles")
    lines.append("")
    for ref in lock.asset_refs:
        lines.append(f"- `{ref.role}`: `{ref.path}`")
    lines.append("")
    lines.append("## Renderer Geometry")
    lines.append("")
    for role, dims in lock.renderer_geometry.items():
        dims_str = ", ".join(f"{k}: {v}" for k, v in dims.items())
        lines.append(f"- `{role}`: {dims_str}")
    lines.append("")
    lines.append("## Rejected Topic 4 Patterns")
    lines.append("")
    lines.append("- Fake inline `<svg>` in `title-logo` div")
    lines.append("- Text-only `RAI` in `content-bug` div")
    lines.append("- Missing `<meta name=\"presentation-template\">` tag")
    lines.append("- Missing `<meta name=\"presentation-template-sha256\">` tag")
    lines.append("- Empty brand asset SHA-256")
    lines.append("- Scaffold prose `Use the visual role`")
    lines.append("- `Prepared by Nikolaos Vasiloglou` on non-title slide")
    lines.append("")
    lines.append("## Gate Result")
    lines.append("")
    if lock.findings:
        for finding in lock.findings:
            icon = "BLOCKER" if finding.severity == "blocker" else "WARNING"
            lines.append(f"- [{icon}] `{finding.code}`: {finding.message}")
    else:
        lines.append("All brand template checks passed.")
    lines.append("")
    return "\n".join(lines)


def _build_receipt(lock: BrandTemplateLock, reference_deck_path: str) -> dict:
    findings_list = [
        {
            "code": f.code,
            "severity": f.severity,
            "message": f.message,
            "path": f.path,
        }
        for f in lock.findings
    ]
    blocker_count = sum(1 for f in lock.findings if f.severity == "blocker")
    return {
        "schema_version": 1,
        "receipt_type": "conference_pipeline.presentation.brand_template_lock",
        "generated_at": lock.generated_at,
        "generated_by": "scripts/presentations/lock_brand_template.py",
        "reference_name": lock.reference_name,
        "reference_deck_path": lock.reference_deck_path or reference_deck_path,
        "reference_deck_sha256": lock.reference_deck_sha256,
        "status": "blocked" if blocker_count > 0 else "succeeded",
        "asset_sha256": lock.template_sha256,
        "renderer_geometry": lock.renderer_geometry,
        "css_variables": lock.css_variables,
        "findings": findings_list,
        "blocker_count": blocker_count,
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Write brand reference lock artifacts.")
    parser.add_argument("--workspace", type=Path, required=True, help="Workspace root path.")
    parser.add_argument("--deck-dir", type=Path, required=True, help="Deck directory to validate.")
    parser.add_argument("--reference-deck", type=Path, default=None, help="Reference deck HTML path.")
    parser.add_argument("--output-md", type=Path, required=True, help="Output Markdown path.")
    parser.add_argument("--output-json", type=Path, required=True, help="Output JSON path.")
    parser.add_argument(
        "--expected-blockers",
        type=str,
        default="",
        help="Comma-separated list of expected blocker codes (exit 0 even if these fire).",
    )
    parser.add_argument("--dry-run", action="store_true", help="Print what would be written; write nothing.")
    parser.add_argument("--summary", action="store_true", help="Print summary to stdout after writing.")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    workspace = args.workspace.expanduser().resolve()

    try:
        deck_dir = _resolve_inside_workspace(workspace, args.deck_dir, label="--deck-dir")
        output_md = args.output_md
        output_json = args.output_json
    except ValueError as exc:
        print(f"Path error: {exc}", file=sys.stderr)
        return 2

    if args.dry_run:
        print(json.dumps({
            "workspace": str(workspace),
            "would_write": [str(output_md), str(output_json)],
        }, indent=2))
        return 0

    # Always read HTML from --deck-dir (the deck being validated for brand issues)
    html_content = ""
    target_deck_path = ""
    if deck_dir.is_dir():
        for candidate in sorted(deck_dir.glob("*.html")):
            html_content = candidate.read_text(encoding="utf-8")
            target_deck_path = str(candidate)
            break

    # --reference-deck sets the reference path metadata; does not override the validation target
    reference_deck_path = target_deck_path
    if args.reference_deck:
        ref_path = Path(args.reference_deck).expanduser()
        if not ref_path.is_absolute():
            ref_path = workspace / ref_path
        if ref_path.exists():
            reference_deck_path = str(ref_path)

    assets_sha256 = brand_assets_sha256()

    lock = validate_brand_template_lock(
        html_content=html_content,
        assets_sha256=assets_sha256,
        reference_name=BRAND_REFERENCE_NAME,
        reference_deck_path=reference_deck_path,
    )

    md_content = _build_markdown(lock, reference_deck_path)
    receipt = _build_receipt(lock, reference_deck_path)

    output_md = Path(output_md)
    output_json = Path(output_json)
    output_md.parent.mkdir(parents=True, exist_ok=True)
    output_md.write_text(md_content, encoding="utf-8")
    _write_atomic(output_json, receipt)

    if args.summary:
        print(json.dumps({"status": lock.status, "blocker_count": receipt["blocker_count"]}, indent=2))

    expected = {c.strip() for c in args.expected_blockers.split(",") if c.strip()}
    actual_blockers = {f.code for f in lock.findings if f.severity == "blocker"}
    unexpected = actual_blockers - expected
    if unexpected:
        print(f"Unexpected blockers: {sorted(unexpected)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
