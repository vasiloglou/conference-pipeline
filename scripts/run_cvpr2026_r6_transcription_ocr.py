#!/usr/bin/env python3
"""Run the fixed-path CVPR r6 transcription/PDF/OCR owner.

This command accepts no source URL, discovery pattern, arbitrary payload path,
host, cookie, or model override.  It reads only the named r6 receipts, then
hands their declared local payload rows to the receipt-aware executor.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from conference_pipeline.acquisition.cvpr_r6_artifact_contract import R6ArtifactContract
from conference_pipeline.acquisition.cvpr_r6_stage_admission import (
    admit_fixed_r6_pre_provider,
)
from conference_pipeline.model_governance.registry import load_registry
from conference_pipeline.r6_transcription_ocr_execution import (
    R6ExecutionError,
    build_live_r6_provider,
    execute_r6_declared_local,
    execute_r6_no_paid_lane,
)
from conference_pipeline.transcription_ocr import atomic_write_json


# These expressions are deliberately finite credential syntax, not a generic
# secret scanner.  Each accepted separator is explicit so repeated separators
# (for example ``api---key``) cannot be normalized into a credential label.
_API_KEY_LABEL = re.compile(
    r"(?:api[-_ ]key|x[-_ ]api[-_ ]key)", re.IGNORECASE
)
_API_KEY_ASSIGNMENT = re.compile(
    r"(?<![A-Za-z0-9_-])(?:api[-_ ]key|x[-_ ]api[-_ ]key)\s*[:=]\s*\S+",
    re.IGNORECASE,
)
_AUTHORIZATION_BEARER_ASSIGNMENT = re.compile(
    r"(?<![A-Za-z0-9_-])authorization\s*[:=]\s*bearer\s+\S+", re.IGNORECASE
)
_CREDENTIAL_ASSIGNMENT = re.compile(
    r"(?<![A-Za-z0-9_-])(?:cookie|password|token|secret)\s*[:=]\s*\S+",
    re.IGNORECASE,
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--mode",
        choices=("speech-benchmark-only", "ocr-benchmark-only", "full"),
        required=True,
    )
    return parser


def _fixed_path(contract: R6ArtifactContract, key: str) -> Path:
    return contract.path(key)


def _read_sanitized_receipt(path: Path, *, label: str) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise R6ExecutionError(f"{label} receipt must be readable JSON") from exc
    if not isinstance(payload, dict):
        raise R6ExecutionError(f"{label} receipt must be a JSON object")
    forbidden_key_fragments = (
        "cookie",
        "password",
        "secret",
        "token",
        "authorization",
        "api_key",
    )
    def is_finite_api_key_label(value: object) -> bool:
        return isinstance(value, str) and _API_KEY_LABEL.fullmatch(value) is not None

    def contains_structured_raw_credential(value: str) -> bool:
        """Recognize only finite, delimiter-qualified credential syntax.

        Receipt prose is allowed to discuss ordinary words such as ``token``
        or ``API key``.  A raw string becomes credential-shaped only when a
        finite label is paired with an assignment/header delimiter and a
        nonempty value.  The established CVPR cookie-file marker remains an
        explicit special case because it names an unsafe credential carrier,
        rather than relying on a broad ``cookie`` substring rule.
        """

        return bool(
            _API_KEY_ASSIGNMENT.search(value)
            or _AUTHORIZATION_BEARER_ASSIGNMENT.search(value)
            or _CREDENTIAL_ASSIGNMENT.search(value)
            or "cvpr2026_virtual_cookies_file" in value.casefold()
        )

    def contains_secretish(value: object) -> bool:
        if isinstance(value, Mapping):
            for key, child in value.items():
                # This canonical, false-only attestation is generated by the
                # fixed r6 envelopes.  A spelling variant or any other value
                # remains a forbidden secret-shaped key.
                if key == "secrets_copied" and child is False:
                    continue
                if (
                    any(marker in str(key).lower() for marker in forbidden_key_fragments)
                    or is_finite_api_key_label(key)
                ):
                    return True
                if contains_secretish(child):
                    return True
            return False
        if isinstance(value, list):
            return any(contains_secretish(child) for child in value)
        if isinstance(value, str):
            return contains_structured_raw_credential(value)
        return False

    if contains_secretish(payload):
        raise R6ExecutionError(f"{label} receipt is not sanitized")
    return payload


def _declared_charge_map(estimate_receipt: Mapping[str, Any]) -> dict[str, float]:
    """Read only an explicit finite per-call maximum from the estimate receipt."""

    candidate = estimate_receipt.get("maximum_charge_usd_by_task")
    if not isinstance(candidate, Mapping):
        raise R6ExecutionError("estimate receipt lacks maximum_charge_usd_by_task for r6 dispatch")
    charges: dict[str, float] = {}
    for task_id, value in candidate.items():
        if (
            isinstance(task_id, str)
            and isinstance(value, (int, float))
            and not isinstance(value, bool)
        ):
            charges[task_id] = float(value)
    return charges


def _receipt_digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _execution_envelope(
    *,
    admission: Any,
    kind: str,
    receipt_payloads: list[object],
    processing_inventory_path: Path,
) -> dict[str, Any]:
    """Bind a settled execution to the exact pre-provider admission state."""

    return {
        **dict(admission.envelope),
        "receipt_type": f"conference_pipeline.cvpr2026_r6_{kind}",
        "kind": kind,
        "status": "succeeded",
        # ``policy_digest`` is retained as a deliberately named compatibility
        # binding for the final stage contract; it equals the material policy,
        # never the independently governed audio policy.
        "policy_digest": admission.material_policy_digest,
        "processing_inventory_path": processing_inventory_path.name,
        "processing_inventory_sha256": _receipt_digest(processing_inventory_path),
        "receipts": receipt_payloads,
        "secrets_copied": False,
    }


def _terminal_ledger(*, contract: R6ArtifactContract, envelope: Mapping[str, Any]) -> dict[str, Any]:
    """Create the canonical zero-dispatch ledger for the terminal lane."""

    payload: dict[str, Any] = {
        "schema_version": 1,
        "run_id": contract.run_id,
        "ledger_type": "r6_committed_plus_actual",
        "status": "not_applicable",
        "canonical_prior_spend_usd": 0.0,
        "reservations": [],
        "committed": [],
        "actuals": [],
        "queue_digest": envelope["queue_digest"],
        "dispatch_schedule_digest": None,
        "policy_digest": envelope["material_policy_digest"],
        "audio_policy_digest": envelope["audio_policy_digest"],
        "secrets_copied": False,
    }
    digest_payload = {key: value for key, value in payload.items() if key != "ledger_sha256"}
    payload["ledger_sha256"] = hashlib.sha256(
        json.dumps(digest_payload, sort_keys=True, separators=(",", ":"), allow_nan=False).encode(
            "utf-8"
        )
    ).hexdigest()
    return payload


def run_fixed_r6_execution(
    *, mode: str, contract: R6ArtifactContract | None = None
) -> dict[str, Any]:
    """Load only fixed receipt paths and invoke the governed live owner."""

    artifact_contract = contract or R6ArtifactContract.production()
    admission = admit_fixed_r6_pre_provider(mode=mode, contract=artifact_contract)
    root = artifact_contract.workspace
    if admission.mode == "no-paid-lane":
        # No configuration/provider construction is even imported for a
        # terminal no-paid state.  These fixed receipts make that completion
        # explicit instead of fabricating an empty successful paid lane.
        audio = _read_sanitized_receipt(
            _fixed_path(artifact_contract, "audio_recovery_receipt"), label="audio"
        )
        material = _read_sanitized_receipt(
            _fixed_path(artifact_contract, "material_acquisition_receipt"), label="material"
        )
        result = execute_r6_no_paid_lane(
            workspace=root,
            audio_receipt=audio,
            material_acquisition_receipt=material,
            policy_digest=admission.material_policy_digest,
            audio_policy_digest=admission.audio_policy_digest,
            inventory_path=_fixed_path(artifact_contract, "processing_inventory"),
            artifact_contract=artifact_contract,
        )
        terminal = {
            **dict(admission.envelope),
            "policy_digest": admission.material_policy_digest,
            "processing_inventory_path": artifact_contract.relative_path("processing_inventory").as_posix(),
            "processing_inventory_sha256": _receipt_digest(
                _fixed_path(artifact_contract, "processing_inventory")
            ),
            "receipts": [],
            "secrets_copied": False,
        }
        atomic_write_json(_fixed_path(artifact_contract, "cost_estimate_receipt"), terminal)
        atomic_write_json(_fixed_path(artifact_contract, "benchmark_receipt"), terminal)
        atomic_write_json(_fixed_path(artifact_contract, "provider_receipts"), terminal)
        atomic_write_json(
            _fixed_path(artifact_contract, "budget_ledger"),
            _terminal_ledger(contract=artifact_contract, envelope=terminal),
        )
        return {**result, "envelope": terminal}
    audio = _read_sanitized_receipt(
        _fixed_path(artifact_contract, "audio_recovery_receipt"), label="audio"
    )
    material = _read_sanitized_receipt(
        _fixed_path(artifact_contract, "material_acquisition_receipt"), label="material"
    )
    estimate = _read_sanitized_receipt(
        _fixed_path(artifact_contract, "cost_estimate_receipt"), label="estimate"
    )

    # Imported only after all local, sanitized receipt checks pass.  A live
    # operator is responsible for making credentials available before this
    # command is invoked; this plan never invokes the command.
    from conference_pipeline.config import load_settings

    provider = build_live_r6_provider(load_settings())
    result = execute_r6_declared_local(
        workspace=root,
        audio_receipt=audio,
        material_acquisition_receipt=material,
        policy_digest=admission.material_policy_digest,
        audio_policy_digest=admission.audio_policy_digest,
        ledger_path=_fixed_path(artifact_contract, "budget_ledger"),
        provider_receipts_path=_fixed_path(artifact_contract, "provider_receipts"),
        inventory_path=_fixed_path(artifact_contract, "processing_inventory"),
        registry=load_registry(),
        provider=provider,
        maximum_charge_usd_by_task=_declared_charge_map(estimate),
        dispatch_schedule=admission.schedule,
        prior_benchmarked_tasks=admission.settled_benchmark_tasks,
        mode="benchmark-only" if admission.mode == "bootstrap" else "full",
        benchmark_task=admission.benchmark_task,
        artifact_contract=artifact_contract,
    )
    if result["status"] == "succeeded":
        provider_payload = _read_sanitized_receipt(
            _fixed_path(artifact_contract, "provider_receipts"), label="provider"
        )
        receipts = provider_payload.get("receipts", [])
        if not isinstance(receipts, list):
            raise R6ExecutionError("r6 execution provider receipt rows are malformed")
        kind = "benchmark" if admission.mode == "bootstrap" else "provider"
        envelope = _execution_envelope(
            admission=admission,
            kind=kind,
            receipt_payloads=receipts,
            processing_inventory_path=_fixed_path(artifact_contract, "processing_inventory"),
        )
        if admission.mode == "bootstrap":
            atomic_write_json(_fixed_path(artifact_contract, "benchmark_receipt"), envelope)
        atomic_write_json(
            _fixed_path(artifact_contract, "provider_receipts"),
            {**envelope, "receipt_type": "conference_pipeline.cvpr2026_r6_provider"},
        )
        return {**result, "execution_envelope": envelope}
    return result


def main() -> int:
    args = build_parser().parse_args()
    result = run_fixed_r6_execution(mode=args.mode)
    print(json.dumps({"status": result["status"], "mode": result["mode"]}, sort_keys=True))
    return 0 if result["status"] == "succeeded" else 2


if __name__ == "__main__":  # pragma: no cover - live invocation is a later plan.
    raise SystemExit(main())
