#!/usr/bin/env python3
"""Frozen source references, matched cloud baselines, hybrid synthesis, and blind evaluation."""

from __future__ import annotations

import argparse
import fcntl
import json
import os
from pathlib import Path
from types import SimpleNamespace

from conference_pipeline.analysis.local_summary_benchmark import (
    SCHEMA_KEYS,
    Budget,
    Calls,
    digest,
    pack,
    sentence_spans,
    summary_prompt,
    validate_summary,
    write_json,
)
from conference_pipeline.indexing.token_policy import token_count


def original_source(row):
    return {k: row[k] for k in ("unit_id", "text", "source_artifact_id", "metadata") if k in row}


def references(data, calls, out, sample=40):
    rows = data["rows"]
    chosen = [
        original_source(rows[i * len(rows) // min(sample, len(rows))])
        for i in range(min(sample, len(rows)))
    ]
    units = []
    for i in range(0, len(chosen), 5):
        batch = chosen[i : i + 5]
        by_id = {r["unit_id"]: r for r in batch}
        prompt = (
            "Build a blinded source-grounded evaluation reference, without seeing any candidate summaries. "
            "For EVERY source return its 1-3 most important substantive findings; include negative findings, exact quantitative conditions, caveats. "
            'Select supporting sentence IDs. No assumptions from general knowledge. Return JSON {"units":[{"unit_id":"id",'
            '"findings":[{"finding":"fact to test recall of", "evidence_sentence_ids":["s2"], "kind":"method|result|caveat|negative"}]}]}.\n'
            + json.dumps(
                [
                    {
                        **{k: v for k, v in r.items() if k != "text"},
                        "sentences": sentence_spans(r["text"]),
                    }
                    for r in batch
                ]
            )
        )

        def check(p):
            if {u.get("unit_id") for u in p.get("units", [])} != set(by_id) or len(
                p["units"]
            ) != len(by_id):
                raise ValueError("reference_accounting")
            for u in p["units"]:
                if not isinstance(u.get("findings"), list) or not 1 <= len(u["findings"]) <= 3:
                    raise ValueError("missing_findings")
                for f in u["findings"]:
                    sentences = {
                        s["sentence_id"]: s for s in sentence_spans(by_id[u["unit_id"]]["text"])
                    }
                    ids = f.get("evidence_sentence_ids")
                    if (
                        not f.get("finding")
                        or not isinstance(ids, list)
                        or not ids
                        or not set(ids) <= set(sentences)
                    ):
                        raise ValueError("reference_sentence_id_invalid")

        result = calls(prompt, check, cloud_alias="sol", purpose="evaluation")
        for u in result["units"]:
            sentences = {s["sentence_id"]: s for s in sentence_spans(by_id[u["unit_id"]]["text"])}
            for f in u["findings"]:
                f["quote"] = "\n".join(sentences[s]["text"] for s in f["evidence_sentence_ids"])
        units.extend(result["units"])
    questions = [
        "What are the central research themes and the evidence for each?",
        "Which distinct mechanisms are proposed, and how do they work?",
        "Which datasets or experimental settings support the findings?",
        "Which quantitative improvements are reported, under what conditions?",
        "Which negative results or failure modes qualify the main claims?",
        "What caveats limit generalization beyond the evaluated conditions?",
        "Which findings contradict or qualify other sources?",
        "Which minority findings challenge the dominant narrative?",
        "Which conclusions have support from genuinely independent sources?",
        "Which apparent disagreements arise from different experimental settings?",
        "What important questions remain unanswered by this evidence?",
        "Which source-grounded connections are useful for downstream deep analysis?",
    ]
    payload = {
        "source_sha256": digest(data["rows"]),
        "sampled_units": chosen,
        "references": units,
        "questions": questions,
        "limitations": "Sampled reference, not exhaustive gold standard; generated by an independent cloud model.",
    }
    write_json(out, payload)


def cloud_baseline(data, calls, out, alias="luna"):
    ids = {r["unit_id"] for r in data["rows"]}

    def builder(rs):
        return summary_prompt(data["title"] + " / " + data["category"], rs)

    chunks = pack(data["rows"], builder, calls.count, calls.ceiling)
    if len(chunks) != 1:
        raise ValueError(
            "baseline_requires_one_bounded_input; use matched sample or saved full baseline"
        )
    p = calls(builder(chunks[0]), lambda p: validate_summary(p, ids), cloud_alias=alias)
    write_json(out, p)


def hybrid(data, calls, source, out, evidence_mode="ledger"):
    ids = {r["unit_id"] for r in data["rows"]}
    p = json.loads(source.read_text())
    ledger_path = source.parent / "ledger.json"
    records = (
        json.loads(ledger_path.read_text())["claims"]
        if evidence_mode == "ledger" and ledger_path.exists()
        else []
    )

    # The full ledger must fit; never silently cherry-pick evidence for the cloud final pass.
    def builder(rs):
        return summary_prompt(
            data["title"]
            + "; critically synthesize local analysis with source-grounded claim ledger",
            [{"draft": p}] + rs,
        )

    selected = []
    for record in records:
        if calls.count(builder(selected + [record])) <= calls.ceiling:
            selected.append(record)
    if evidence_mode == "summary-packs" or (records and len(selected) != len(records)):
        packs_path = source.parent / "synthesis_packs.json"
        if not packs_path.exists():
            raise ValueError("hybrid_ledger_exceeds_context; missing bounded thematic packs")
        levels = json.loads(packs_path.read_text())["levels"]
        eligible = [level for level in levels if calls.count(builder(level)) <= calls.ceiling]
        if not eligible:
            raise ValueError("hybrid_no_complete_reduction_level_fits")
        selected = eligible[0]
        write_json(
            out.with_suffix(".input-coverage.json"),
            {
                "mode": "complete_bounded_reduction_level",
                "original_ledger_claims": len(records) if evidence_mode == "ledger" else None,
                "evidence_mode": evidence_mode,
                "synthesis_pack_count": len(selected),
                "source_ledger": str(ledger_path),
                "limitation": "Cloud final sees local synthesis packs; original ledger remains external. Compression can omit evidence.",
            },
        )
    final = calls(builder(selected), lambda p: validate_summary(p, ids), cloud_alias="luna")
    write_json(out, final)


def rubric_sources_for_candidates(by_id, sampled_units, anonymized):
    serialized = json.dumps(anonymized)
    evidence_ids = {r["unit_id"] for r in sampled_units}
    evidence_ids.update(u for u in by_id if u in serialized)
    return [by_id[u] for u in sorted(evidence_ids)]


def evaluate(data, calls, reference, candidates, out):
    ref = json.loads(reference.read_text())
    if ref["source_sha256"] != digest(data["rows"]):
        raise ValueError("evaluation_source_fingerprint_mismatch")
    results = []
    by_id = {r["unit_id"]: original_source(r) for r in data["rows"]}
    anonymized = {
        str(path): {k: json.loads(path.read_text())[k] for k in SCHEMA_KEYS} for path in candidates
    }
    for candidate in candidates:
        p = anonymized[str(candidate)]
        ids = {r["unit_id"] for r in data["rows"]}
        run_path = candidate.parent / "run.json"
        if run_path.exists():
            lineage = json.loads(run_path.read_text())
            expected = digest(sorted(data["rows"], key=lambda r: r["unit_id"]))
            if (
                lineage.get("evidence_set_sha256") is not None
                and lineage["evidence_set_sha256"] != expected
            ):
                raise ValueError("candidate_evidence_set_mismatch")
        validate_summary(p, ids)
        # Atomic recall/support assessments with quotes; no score inferred from citation counts.
        for i in range(0, len(ref["references"]), 5):
            selected = ref["references"][i : i + 5]
            source_ids = {r["unit_id"] for r in selected}
            sources = [r for r in ref["sampled_units"] if r["unit_id"] in source_ids]
            prompt = (
                "Independently audit an anonymous synthesis against original evidence and frozen findings. "
                "For each reference finding return recalled=true only if the synthesis accurately conveys it. "
                'Return JSON {"findings":[{"unit_id":"id","finding_index":0,"recalled":true,"reason":"..."}]}.\n'
                "REFERENCES:"
                + json.dumps(selected)
                + "\nSOURCES:"
                + json.dumps(sources)
                + "\nANONYMOUS SYNTHESIS:"
                + json.dumps(p)
            )
            expected = {(u["unit_id"], j) for u in selected for j, _ in enumerate(u["findings"])}

            def check(result):
                found = result.get("findings", [])
                if (
                    len(found) != len(expected)
                    or {(x.get("unit_id"), x.get("finding_index")) for x in found} != expected
                ):
                    raise ValueError("incomplete_recall_judgment")
                if any(not isinstance(x.get("recalled"), bool) for x in found):
                    raise ValueError("invalid_recall_type")

            result = calls(prompt, check, cloud_alias="sol", purpose="evaluation")
            for finding in result["findings"]:
                source = by_id[finding["unit_id"]]
                finding["source_artifact_id"] = source.get("source_artifact_id", finding["unit_id"])
            results.append({"candidate": str(candidate), "packet": i, "claim_audit": [], **result})
        evidence = p["notable_evidence"]
        n = min(40, len(evidence))
        selected = [evidence[i * len(evidence) // n] for i in range(n)] if n else []
        for i in range(0, len(selected), 5):
            batch = selected[i : i + 5]
            source_ids = {u for claim in batch for u in claim["unit_ids"]}
            sources = [by_id[u] for u in sorted(source_ids)]
            prompt = (
                "Audit EVERY numbered claim against its cited original sources. Exact source IDs alone are not proof. "
                "Check entailment, numbers, experimental conditions, attribution, omitted caveats and unsupported generalization. "
                'Return JSON {"claim_audit":[{"claim_index":0,"supported":true,"material_numeric_error":false,"reason":"specific evidence"}]}.\n'
                "CLAIMS:" + json.dumps(batch) + "\nORIGINAL SOURCES:" + json.dumps(sources)
            )

            def check_claims(result):
                audit = result.get("claim_audit", [])
                if len(audit) != len(batch) or {c.get("claim_index") for c in audit} != set(
                    range(len(batch))
                ):
                    raise ValueError("incomplete_claim_audit")
                if any(
                    not isinstance(c.get("supported"), bool)
                    or not isinstance(c.get("material_numeric_error"), bool)
                    for c in audit
                ):
                    raise ValueError("invalid_claim_judgment")

            result = calls(prompt, check_claims, cloud_alias="sol", purpose="evaluation")
            results.append(
                {"candidate": str(candidate), "packet": "claim-" + str(i), "findings": [], **result}
            )
    # Paired source-grounded synthesis rubric, order swapped. Small samples only; bounded explicitly.
    pairwise = []
    if len(candidates) == 2:
        # A whole-corpus candidate can cite papers outside the frozen sample.
        # Supply their original evidence, rather than treating absence as falsity.
        rubric_sources = rubric_sources_for_candidates(by_id, ref["sampled_units"], anonymized)
        for order in (list(candidates), list(reversed(candidates))):
            prompt = (
                "Blindly compare two syntheses against source evidence. Ignore length and style unless substantive. "
                "Score each on 1-5 for synthesis, caveats, contradictions, minority_findings, downstream_usefulness. "
                "Answer the supplied research questions from the evidence as the basis for scoring. Return JSON "
                '{"A":{"synthesis":1,"caveats":1,"contradictions":1,"minority_findings":1,"downstream_usefulness":1},'
                '"B":{"synthesis":1,"caveats":1,"contradictions":1,"minority_findings":1,"downstream_usefulness":1},'
                '"reason":"specific evidence-backed comparison","limitations":"uncertainties"}.\n'
                "QUESTIONS:"
                + json.dumps(ref["questions"])
                + "\nCandidates summarize the full corpus. Evidence includes sampled sources and cited sources. "
                "A valid corpus citation is not unsupported merely because it is outside the reference sample. "
                "Distinguish unassessed claims from claims contradicted by original evidence.\nVALID CORPUS IDS:"
                + json.dumps(sorted(by_id))
                + "\nEVIDENCE:"
                + json.dumps(rubric_sources)
                + "\nA:"
                + json.dumps(anonymized[str(order[0])])
                + "\nB:"
                + json.dumps(anonymized[str(order[1])])
            )

            def check(p):
                for label in ["A", "B"]:
                    for key in [
                        "synthesis",
                        "caveats",
                        "contradictions",
                        "minority_findings",
                        "downstream_usefulness",
                    ]:
                        value = p.get(label, {}).get(key)
                        if (
                            isinstance(value, bool)
                            or not isinstance(value, (float, int))
                            or not 1 <= value <= 5
                        ):
                            raise ValueError("invalid_rubric")

            if calls.count(prompt) <= calls.ceiling:
                result = calls(prompt, check, cloud_alias="sol", purpose="evaluation")
                pairwise.append({"order": [str(x) for x in order], **result})
    write_json(
        out,
        {
            "results": results,
            "pairwise": pairwise,
            "status": "pilot_only",
            "limitations": [
                "Independent model judgments require review; exact quotes do not alone prove entailment.",
                "Recall is measured against sampled source findings, not the cloud output as truth.",
            ],
        },
    )


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("mode", choices=["references", "baseline", "hybrid", "evaluate"])
    p.add_argument("--input", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--root", type=Path, required=True)
    p.add_argument("--reference", type=Path)
    p.add_argument("--candidate", type=Path, action="append", default=[])
    p.add_argument("--sample", type=int, default=0)
    p.add_argument("--ceiling", type=int, default=65536)
    p.add_argument("--credential-file", type=Path)
    p.add_argument("--hybrid-evidence", choices=("ledger", "summary-packs"), default="ledger")
    args = p.parse_args()
    if args.credential_file:
        from dotenv import dotenv_values

        # Import only named provider credentials from the documented trusted file, never execute shell code.
        values = dotenv_values(args.credential_file)
        for name in ["OPENAI_API_KEY", "OPENROUTER_API_KEY"]:
            if values.get(name):
                os.environ[name] = values[name]
    data = json.loads(args.input.read_text())
    if args.sample:
        rows = data["rows"]
        n = min(args.sample, len(rows))
        data["rows"] = [rows[i * len(rows) // n] for i in range(n)]
    args.root.mkdir(parents=True, exist_ok=True)
    with (args.root / "experiment.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        budget = Budget(args.root)
        counter = SimpleNamespace(
            count=lambda text: token_count(text) + 128,
            alias="qwen36_local",
            revision="counter-only",
        )
        calls = Calls(args.root, counter, budget, args.ceiling, 8192)
        if args.mode == "references":
            references(data, calls, args.out)
        elif args.mode == "baseline":
            cloud_baseline(data, calls, args.out)
        elif args.mode == "hybrid":
            hybrid(data, calls, args.candidate[0], args.out, args.hybrid_evidence)
        else:
            evaluate(data, calls, args.reference, args.candidate, args.out)


if __name__ == "__main__":
    main()
